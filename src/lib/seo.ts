/**
 * Single source of truth for SEO: canonical origin, indexability, and the
 * list of canonical indexable routes (used by sitemap.ts, robots.ts, and the
 * per-page canonical/OG tags).
 *
 * Canonical home is snowrepublicbrewery.com (the domain will be pointed at this
 * Vercel project at launch). Until then the vercel.app deployment is treated as
 * staging and blocked from indexing — flip NEXT_PUBLIC_SEO_INDEXABLE=true on the
 * production domain deploy to allow indexing (see robots.ts).
 */

export const SITE_URL = (
  process.env.NEXT_PUBLIC_SITE_URL ?? "https://snowrepublicbrewery.com"
).replace(/\/$/, "");

export const SITE_NAME = "Snow Republic Brewery";

/** Generated by app/opengraph-image.tsx (1200×630). Referenced explicitly
 * because defining per-page openGraph suppresses Next's auto file-image merge. */
export const OG_IMAGE = {
  url: "/opengraph-image",
  width: 1200,
  height: 630,
  alt: "Snow Republic Brewery — West Dover, Vermont",
};

/**
 * Whether search engines may index this deployment.
 * - Vercel preview deployments are NEVER indexable.
 * - Otherwise indexing is opt-in via NEXT_PUBLIC_SEO_INDEXABLE=true, so the
 *   interim vercel.app host stays blocked until the real domain is connected.
 */
export const IS_INDEXABLE =
  process.env.VERCEL_ENV !== "preview" &&
  process.env.NEXT_PUBLIC_SEO_INDEXABLE === "true";

/** Absolute URL helper: absolute(`/visit`) -> https://…/visit */
export function absolute(path = "/"): string {
  return new URL(path, SITE_URL).toString();
}

/**
 * Builds a page's Metadata with a self-referencing absolute canonical plus
 * matching Open Graph + Twitter tags. `title` is the short page title (the root
 * layout's template appends "· Snow Republic Brewery" to the <title>); OG/Twitter
 * titles are made self-contained. `path` is the canonical route (e.g. "/visit").
 */
export function pageMetadata({
  title,
  description,
  path,
}: {
  title: string;
  description: string;
  path: string;
}): import("next").Metadata {
  const socialTitle = title.includes(SITE_NAME)
    ? title
    : `${title} · ${SITE_NAME}`;
  return {
    title,
    description,
    alternates: { canonical: path },
    openGraph: {
      type: "website",
      siteName: SITE_NAME,
      locale: "en_US",
      url: path,
      title: socialTitle,
      description,
      images: [OG_IMAGE],
    },
    twitter: {
      card: "summary_large_image",
      title: socialTitle,
      description,
      images: [OG_IMAGE.url],
    },
  };
}

export type RouteMeta = {
  path: string;
  changeFrequency:
    | "always"
    | "hourly"
    | "daily"
    | "weekly"
    | "monthly"
    | "yearly"
    | "never";
  priority: number;
};

